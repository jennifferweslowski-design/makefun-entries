// The token radar's model (radar-2): one snapshot of the protocol universe in,
// one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a
// ceiling) plus every other pre-token protocol the radar can rank: 198 rows in
// this snapshot. A protocol is pre-token when its record carries no token (no
// market cap, no CoinGecko id, no symbol). Wrapped, staked and bridged products
// of a token that already trades are set aside, not ranked: WBTC is Bitcoin on
// Ethereum, Binance staked ETH is ETH in a staking product, and neither is a
// protocol still waiting on a launch of its own. The same rule the house used
// for the watchlist decides it here, from the snapshot's own fields: category
// Bridge, Canonical Bridge, Liquid Staking, Liquid Restaking, Restaked BTC or
// CEX; a name carrying a whole word wrapped, staked or staking; a name starting
// with an exchange's name; a name ending in a version marker. The snapshot's
// live-token protocols are kept apart and shown as the market's own values,
// never mixed into the ranked board.
//
// Implied value is calibrated, not asserted. For each category, the base
// multiple is the median market-cap-to-TVL ratio of that category's live-token
// protocols in this same snapshot (at least three comparables, else the global
// median over all live, non-CEX protocols); the multiple is clamped to
// [0.05, 2.0] so one odd comparable cannot set the price. Then:
//
//   base       = tvl_usd x category_multiple
//   growth     = clamp(change_7d, -60, 120) per cent
//   growthMult = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity   = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age_days unknown: 365)
//   implied    = max(1, round(base x growthMult x maturity))
//
// No protocol name is ever special-cased: the same function scores every row,
// and the dashboard shows each row's multiple, its comparable count and every
// multiplier, so a reader can check the arithmetic.

